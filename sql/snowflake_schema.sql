-- Run in an explicitly selected sandbox database/schema. No warehouse is created.
CREATE TABLE IF NOT EXISTS EDITION_SNAPSHOTS (
  DATASET_ID VARCHAR NOT NULL, READER_ID VARCHAR NOT NULL, BRAND VARCHAR NOT NULL,
  SUBSCRIBED BOOLEAN NOT NULL, SNAPSHOT_DATE DATE NOT NULL, STARTED_DATE DATE NOT NULL,
  OBSERVED_UNTIL DATE NOT NULL, SPLIT_NAME VARCHAR NOT NULL
);
CREATE TABLE IF NOT EXISTS EDITION_EVENTS (
  DATASET_ID VARCHAR NOT NULL, READER_ID VARCHAR NOT NULL, EVENT_DATE DATE NOT NULL, EVENT_TYPE VARCHAR NOT NULL
);
